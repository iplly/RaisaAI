#include <nlohmann/json.hpp>
#include <string>

using json = nlohmann::json;

json toolDef(const std::string &name, const std::string &description,
             const json &parameters) {
  return {{"type", "function"},
          {"function",
           {{"name", name},
            {"description", description},
            {"parameters", parameters}}}};
}

